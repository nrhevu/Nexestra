// Turn the drizzle-kit output in `drizzle/` into a TypeScript module.
//
// The server is bundled with esbuild into a single file, so resolving the
// migration folder from `import.meta.url` at runtime would break in production.
// Embedding the statements keeps dev (tsx), tests and the bundle identical.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

export async function readMigrations() {
  const dir = join(root, "drizzle");
  const files = (await readdir(dir)).filter((name) => name.endsWith(".sql")).sort();
  const migrations = [];
  for (const file of files) {
    const sql = await readFile(join(dir, file), "utf8");
    const statements = sql
      .split("--> statement-breakpoint")
      .map((statement) => statement.trim())
      .filter(Boolean);
    migrations.push({ tag: file.replace(/\.sql$/, ""), statements });
  }
  return migrations;
}

function render(migrations) {
  const body = migrations
    .map(
      (migration) =>
        `  {\n    tag: ${JSON.stringify(migration.tag)},\n    statements: [\n${migration.statements
          .map((statement) => `      ${JSON.stringify(statement)},`)
          .join("\n")}\n    ],\n  },`,
    )
    .join("\n");

  return `// GENERATED by scripts/embed-migrations.mjs — do not edit by hand.
// Run \`pnpm --filter @nexestra/storage db:generate\` after changing src/schema.ts.

export interface Migration {
  tag: string;
  statements: readonly string[];
}

export const MIGRATIONS: readonly Migration[] = [
${body}
];
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const migrations = await readMigrations();
  await writeFile(join(root, "src", "migrations.ts"), render(migrations), "utf8");
  process.stdout.write(
    `embedded ${migrations.length} migration(s): ${migrations.map((m) => m.tag).join(", ")}\n`,
  );
}
